#!/usr/bin/env python3
"""Check the sixty Lagrangian articles against the heading contract.

Reads the articles, not the maps. The maps are derived; this script is the
source of truth. Run from the repository root:

    python3 check_lagrangian_headings.py

Exit status 0 means every article obeys the contract. The counts table of
articles_internal/lagrangian-migration.md is generated by a separate script,
_reserve/lagrangian_slots.py, which reads the same articles.
"""

import glob
import itertools
import os
import re
import sys

# Slots that may carry more than one section: 3 when the action is stated in
# blocks, 4 when the variation is run twice or closes with the bracket
# decomposition, 7 in three fluid articles, 9 when a current is denied as well
# as stated, 12 when the ledger separates what the method adds from what the
# chart adds.
REPEATABLE = ('3', '4', '7', '9', '12', 'KEEP')

MANDATORY = [
    ('1', 'Introduction'),
    ('2', 'Conventions'),
    ('3', 'The Action in '),
    ('4', 'The Variation'),
    ('7', 'The Structural Consequence'),
    ('9', 'The Noether Currents'),
    ('12', 'What the Principle Adds and What It Relabels'),
    ('15', 'Summary'),
    ('16', 'Summary of Notation'),
    ('17', 'Further Reading'),
]

CONDITIONAL = []

# The spine, in order. Slot 5 is retired.
CANONICAL = [
    ('1', 'Introduction'),
    ('2', 'Conventions'),
    ('3', 'The Action in '),
    ('4', 'The Variation'),
    ('6', 'The Constraints the Action Imposes'),
    ('7', 'The Structural Consequence'),
    ('9', 'The Noether Currents'),
    ('M3', 'The Legendre Transform'),
    ('10', 'The Two Settings'),
    ('11', 'The Limits and the Truncation\u2019s Error'),
    ('12', 'What the Principle Adds and What It Relabels'),
    ('13', 'Comparisons with Other Formulations'),
    ('P2', 'The Reconstruction and Its Limits'),
    ('14', 'Open Questions'),
    ('15', 'Summary'),
    ('16', 'Summary of Notation'),
    ('17', 'Further Reading'),
    ('KEEP', 'Aside:'),
    ('KEEP', 'Verification'),
]

# The QCD article is the only sector article. Its nine sections depend on
# individual slots -- the covariant derivative on slot 3, gauge fixing on slot
# 6, the vertices on slot 7 -- so they interleave by necessity and are checked
# for internal order only, never for position on the spine.
SECTOR = [
    ('S1', 'Why Three Colours'),
    ('S2', 'The Triplet, the Antitriplet and the Octet'),
    ('S3', 'The Generators and the Normalisation'),
    ('S4', 'The Covariant Derivative and the Field Strength'),
    ('S5', 'Gauge Fixing and the Ghost'),
    ('S6', 'The Feynman Rules'),
    ('S7', 'The Three Vertices Derived'),
    ('S8', 'The Colour Factors'),
    ('S9', 'The Algebra Verified'),
]

CANONICAL_BY_LENGTH = sorted(CANONICAL, key=lambda x: -len(x[1]))
RANK = {s: i for i, s in enumerate(dict.fromkeys(s for s, _ in CANONICAL + SECTOR))}
SECTOR_SLOTS = [s for s, _ in SECTOR]


def slot_of(heading):
    for slot, prefix in CANONICAL_BY_LENGTH:
        if heading == prefix or heading.startswith(prefix):
            return slot
    return None


def h2(path):
    out = []
    for line in open(path, encoding='utf-8'):
        if line.startswith('## '):
            out.append(line[3:].strip())
    return out


def h3(path):
    return [l[4:].strip() for l in open(path, encoding='utf-8') if l.startswith('### ')]


def title(path):
    first = open(path, encoding='utf-8').readline()
    return re.sub(r'^#+\s*', '', first).strip().strip('_').strip()


def articles():
    return sorted(p for p in glob.glob('articles_physics/*.md')
                  if title(p).startswith('The Lagrangian and '))


def spine(heads):
    seq = []
    for h in heads:
        s = slot_of(h)
        if s and s not in SECTOR_SLOTS and (not seq or seq[-1] != s):
            seq.append(s)
    return seq


def order_errors(heads):
    """Every pair, not only neighbours: a later slot may never precede an earlier one."""
    errs = []
    seq = spine(heads)
    for a, b in itertools.combinations(seq, 2):
        if RANK[a] > RANK[b]:
            errs.append('out of order: %s before %s' % (b, a))
    return errs


def main():
    arts = articles()
    sector = sorted(p for p in glob.glob('articles_physics/*.md')
                    if 'lagrangian' in title(p).lower()
                    and not title(p).startswith('The Lagrangian and '))
    fail = 0
    for p in arts:
        slug = os.path.basename(p)[:-3]
        heads = h2(p)
        errs = ['unmapped heading: %r' % h for h in heads if slot_of(h) is None]
        for slot, name in MANDATORY:
            n = sum(1 for h in heads if slot_of(h) == slot)
            if n == 0:
                errs.append('mandatory slot %s (%s) absent' % (slot, name))
            elif n > 1 and slot not in REPEATABLE:
                errs.append('slot %s appears %d times' % (slot, n))
        for slot in sorted(set(s for s in (slot_of(h) for h in heads) if s)):
            n = sum(1 for h in heads if slot_of(h) == slot)
            if n > 1 and slot not in REPEATABLE and slot not in [m[0] for m in MANDATORY]:
                errs.append('conditional slot %s appears %d times' % (slot, n))
        errs.extend(order_errors(heads))
        if 'quantum-chromodynamics' in slug:
            subs = h3(p)
            want = [n for _, n in SECTOR]
            if subs != want:
                errs.append('sector subsections are %s; want %s' % (subs, want))
        if errs:
            fail += 1
            print('%s' % slug)
            for e in errs:
                print('    %s' % e)
    print()
    print('articles checked: %d' % len(arts))
    print('articles failing: %d' % fail)
    print('sector and level-0 articles not checked here: %d' % len(sector))
    for p in sector:
        print('    %s' % os.path.basename(p)[:-3])
    return 1 if fail else 0


if __name__ == '__main__':
    sys.exit(main())
